#!/usr/bin/env python3
"""Generate original native constants from the single development profile."""
import hashlib
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'profiles/pcm4-mu1476-display.json'
j=json.loads(source.read_text());r=j['renderer'];o=j['ownership'];c=j['carplay'];safe=c['safe_area']
assert (r['nvss_output_device'],r['layer'],o['context'],o['java_terminal'])==(0,60,900,1)
assert o['projection_displayables']==[60]
assert 0<r['coded_width']<=1024 and 0<r['coded_height']<=1024 and 0<r['fps']<=30
assert 0<=r['priority']<=255
assert safe['width']>0 and safe['height']>0 and safe['x']>=0 and safe['y']>=0
assert safe['x']+safe['width']<=r['coded_width'] and safe['y']+safe['height']<=r['coded_height']
values=dict(OUTPUT=r['nvss_output_device'],LAYER=r['layer'],CONTEXT=o['context'],
    WIDTH=r['coded_width'],HEIGHT=r['coded_height'],FPS=r['fps'],PRIORITY=r['priority'],
    SAFE_X=safe['x'],SAFE_Y=safe['y'],SAFE_W=safe['width'],SAFE_H=safe['height'],
    PORT=j['runtime']['plaintext_port'],TIMEOUT=j['runtime']['frame_timeout_ms'])
text='/* Generated by tools/generate_pcm4_profile.py; runtime unverified. */\n#ifndef PCM4_PROFILE_H\n#define PCM4_PROFILE_H\n'
text+='/* Profile SHA256 '+hashlib.sha256(source.read_bytes()).hexdigest()+' */\n'
for name,value in values.items():
    text+=f'#define PCM4_CFG_{name} {int(value)}\n'
for name,value in dict(NVSS_HASH=j['nvss_sha256'],AIRPLAY_HASH=j['airplay_sha256'],
    MARKER=o['java_system_properties']['pcm4.cluster.marker']).items():
    text+=f'#define PCM4_CFG_{name} {json.dumps(value)}\n'
text+='#endif\n'
(ROOT/'native/pcm4_profile.h').write_text(text)
print('Generated native/pcm4_profile.h')
